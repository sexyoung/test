#!/usr/bin/env python3
"""Real local image-conditioned shape inference, not a fixed cat mesh.

Run with the isolated environment made by setup.py. Geometry is generated by
Hunyuan3D-2mini/MLX; optional photo-color projection is an approximation of only
visible colors, and does not recover an unseen back side or produce a rig.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import sys
import time

CACHE = Path(os.environ.get('PHOTO_CAT_MLX_CACHE', str(Path.home() / 'Library/Caches/sunlit-photo-cat-mlx')))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('image', type=Path)
    parser.add_argument('--out', type=Path, required=True)
    parser.add_argument('--weights', type=Path, default=CACHE / 'weights/shape-small')
    parser.add_argument('--faces', type=int, default=6000)
    parser.add_argument('--steps', type=int, default=30)
    parser.add_argument('--resolution', type=int, choices=[128, 192, 256], default=192)
    parser.add_argument('--seed', type=int, default=0)
    parser.add_argument('--skip-background-removal', action='store_true')
    parser.add_argument('--project-colors', action='store_true')
    args = parser.parse_args()
    if not 1000 <= args.faces <= 20000 or not 10 <= args.steps <= 50:
        parser.error('faces must be 1000–20000 and steps must be 10–50')
    if not args.image.is_file() or args.image.stat().st_size > 20 * 1024 * 1024:
        parser.error('input must exist and be no larger than 20 MiB')
    source = CACHE / 'runtime/python/shape'
    if not source.is_dir() or not (args.weights / 'model.fp16.safetensors').is_file():
        parser.error('MLX runtime/weights not installed; run server/photo-cat-mlx/setup.py first')
    sys.path.insert(0, str(source))
    from PIL import Image, ImageOps
    import numpy as np
    import mlx.core as mx
    from hy3dmlx.pipeline import Hunyuan3DShapePipeline
    Image.MAX_IMAGE_PIXELS = 16_000_000
    started = time.monotonic()
    image = ImageOps.exif_transpose(Image.open(args.image))
    if image.width * image.height > 16_000_000 or min(image.size) < 32:
        parser.error('image must have at least 32px per side and at most 16 megapixels')
    image = image.convert('RGBA')
    image.thumbnail((1536, 1536), Image.Resampling.LANCZOS)
    alpha = np.asarray(image.getchannel('A'))
    if alpha.min() == 255 and not args.skip_background_removal:
        print('[background] Removing background locally with U2NetP', flush=True)
        os.environ.setdefault('U2NET_HOME', str(CACHE / 'weights/background'))
        from rembg import remove, new_session
        image = remove(image, session=new_session('u2netp'))
    if np.count_nonzero(np.asarray(image.getchannel('A')) > 127) < 128:
        raise ValueError('Foreground mask is empty; correct the mask and try again')
    args.out.parent.mkdir(parents=True, exist_ok=True)
    prepared = args.out.with_suffix('.input.png')
    image.save(prepared)
    print('[load] Hunyuan3D-2mini, 4-bit DiT/DINO, fp16 VAE', flush=True)
    pipe = Hunyuan3DShapePipeline.from_pretrained(str(args.weights), dtype=mx.float16, quantize=4)
    mesh = pipe.generate(str(prepared), num_inference_steps=args.steps,
                         octree_resolution=args.resolution, seed=args.seed,
                         octree_decode=True)
    original_faces = len(mesh.faces)
    # Marching cubes can leave tiny isolated noise. Keep the main surface only
    # when discarded pieces are negligible; never silently remove a whole limb.
    components = mesh.split(only_watertight=False)
    components = sorted(components, key=lambda part: len(part.faces), reverse=True)
    removed_faces = sum(len(part.faces) for part in components[1:])
    if removed_faces > original_faces * .02:
        raise ValueError('Generated shape has substantial disconnected parts; retry with a clearer full-body foreground')
    if components:
        mesh = components[0]
    if original_faces > args.faces:
        mesh = mesh.simplify_quadric_decimation(face_count=args.faces)
    mesh.update_faces(mesh.nondegenerate_faces())
    mesh.update_faces(mesh.unique_faces())
    mesh.remove_unreferenced_vertices()
    # Only fill simple triangle/quad holes; no speculative bridging of body parts.
    import trimesh
    trimesh.repair.fill_holes(mesh)
    trimesh.repair.fix_normals(mesh)
    unique, counts = np.unique(mesh.edges_sorted, axis=0, return_counts=True)
    boundary_edges = int(np.count_nonzero(counts == 1))
    nonmanifold_edges = int(np.count_nonzero(counts > 2))
    component_count = len(mesh.split(only_watertight=False))
    if component_count != 1 or boundary_edges or nonmanifold_edges:
        raise ValueError(f'Generated surface is not closed and connected (parts={component_count}, boundaries={boundary_edges}, nonmanifold={nonmanifold_edges}); retry a clearer foreground')
    if len(mesh.vertices) == 0 or not np.isfinite(mesh.vertices).all():
        raise ValueError('Generation returned an empty or invalid mesh')
    if args.project_colors:
        # Approximate canonical +Z view projection. This is not generative paint:
        # the input-facing surface retains visible colors; unseen faces receive a
        # median foreground color. The metadata explicitly records that limitation.
        rgba = np.asarray(image)
        foreground = rgba[..., 3] > 127
        ys, xs = np.nonzero(foreground)
        crop = rgba[ys.min():ys.max()+1, xs.min():xs.max()+1]
        lo, hi = mesh.bounds
        u = np.clip((mesh.vertices[:, 0] - lo[0]) / max(hi[0] - lo[0], 1e-6), 0, 1)
        v = np.clip(1-(mesh.vertices[:, 1]-lo[1])/max(hi[1]-lo[1],1e-6),0,1)
        x = (u*(crop.shape[1]-1)).astype(int); y = (v*(crop.shape[0]-1)).astype(int)
        sampled = crop[y, x].copy()
        median = np.median(rgba[foreground, :3],axis=0).astype(np.uint8)
        uncertain = (sampled[:,3] < 127) | (mesh.vertex_normals[:,2] < .15)
        sampled[uncertain,:3] = median
        sampled[:,3]=255
        mesh.visual.vertex_colors=sampled
    else:
        mesh.visual.vertex_colors=np.tile([190,197,202,255], (len(mesh.vertices),1))
    metadata={
        'generator':'Hunyuan3D-2mini via Hunyuan3D-Swift Python MLX reference',
        'source_sha256':hashlib.sha256(args.image.read_bytes()).hexdigest(),
        'seed':args.seed,'steps':args.steps,'resolution':args.resolution,
        'input_faces':original_faces,'faces':len(mesh.faces),
        'elapsed_seconds':round(time.monotonic()-started,2),
        'mlx_peak_memory_gb':round(mx.get_peak_memory()/1e9,3),
        'colors':'approximate_front_projection_unseen_median' if args.project_colors else 'untextured',
        'rigged':False,
        'connected_components':component_count, 'watertight':bool(mesh.is_watertight),
        'boundary_edges':boundary_edges, 'nonmanifold_edges':nonmanifold_edges,
        'removed_noise_faces':removed_faces,
    }
    mesh.metadata.update(metadata)
    mesh.export(str(args.out))
    args.out.with_suffix('.json').write_text(json.dumps(metadata,indent=2))
    print(json.dumps(metadata),flush=True)


if __name__ == '__main__':
    main()
